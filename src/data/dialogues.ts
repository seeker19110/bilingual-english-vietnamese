// ──────────────────────────────────────────────────────────────────────────
// HỘI THOẠI MẪU theo từng "bài" (unit CEFR + vòng từ vựng)
//
// Mỗi bài có các cuộc hội thoại CHẤT LƯỢNG, luân phiên A ↔ B (tối đa 15 lượt
// nói mỗi nhân vật = 30 dòng). Hai nhân vật có TÊN riêng phù hợp (speakerA/B) để
// hội thoại tự nhiên. Hội thoại dùng lại ngữ pháp/từ vựng của chính bài đó —
// và thường MỞ ĐẦU bằng vài câu ôn lại chủ đề TRƯỚC rồi mới vào chủ đề mới —
// để học viên nghe – đọc – bắt chước được ngay.
//
// DIALOGUES được tra theo "id": vừa là id của unit CEFR (xem src/data/cefr.ts),
// vừa là id của vòng từ vựng (xem src/data/curriculum.ts). Các id này không trùng
// nhau nên dùng chung một map là đủ.
// ──────────────────────────────────────────────────────────────────────────

// Một dòng thoại: who = 'A' hoặc 'B' (hai người nói luân phiên).
export interface DialogueLine {
  who: 'A' | 'B'
  en: string
  vi: string
}

// Tên nhân vật (song ngữ) — vi để hiển thị chiều A, en cho chiều B.
export interface SpeakerName {
  vi: string
  en: string
}

// Một cuộc hội thoại.
export interface Dialogue {
  titleVi: string
  titleEn: string
  // Tên hai nhân vật (tùy chọn — hội thoại cũ chưa đặt tên vẫn chạy, hiển thị "A"/"B").
  speakerA?: SpeakerName
  speakerB?: SpeakerName
  lines: DialogueLine[]
}

// Rút gọn: tạo 1 dòng thoại.
const d = (who: 'A' | 'B', en: string, vi: string): DialogueLine => ({ who, en, vi })
// Rút gọn: tạo 1 tên nhân vật song ngữ.
const sp = (vi: string, en: string): SpeakerName => ({ vi, en })
// Rút gọn: tạo 1 cuộc hội thoại. Có thể kèm tên hai nhân vật (speakerA, speakerB).
const dlg = (
  titleVi: string,
  titleEn: string,
  lines: DialogueLine[],
  speakerA?: SpeakerName,
  speakerB?: SpeakerName,
): Dialogue => ({ titleVi, titleEn, speakerA, speakerB, lines })

